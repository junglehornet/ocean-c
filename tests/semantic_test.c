static parseResult analyze(char *source, int valid) {
    tokenlist *tokens = scanTokens(source, "semantic-test");
    parseResult p = parseTokens(tokens);
    assert(!p.hasError);
    semanticResult r = analyzeSemantics(&p);
    assert((r.nErrors == 0) == valid);
    free(tokens);
    return p;
}
